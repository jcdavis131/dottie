def write_entries(path: Path | None = None) -> Path:
    target = path or Path(__file__).with_name("plugin_entries.py")
    body = pprint.pformat(build_entries(), width=100, sort_dicts=True)
    target.write_text(_ENTRIES_HEADER + body + "\n", encoding="utf-8")
    return target


if __name__ == "__main__":
    if "--write-entries" in sys.argv:
        print(write_entries())
    else:
        print(json.dumps(check_plugins(), indent=2))
